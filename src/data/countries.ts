/** Placeholder like "(90) 123-45-67", built from the country's phone groups. */
export function getPhonePlaceholder(country: CountryInfo): string {
  const digits = '1234567890123';
  let pos = 0;
  const parts = country.phoneGroups.map((n) => {
    const part = digits.slice(pos, pos + n);
    pos += n;
    return part;
  });
  const [first, ...rest] = parts;
  return rest.length ? `(${first}) ${rest.join('-')}` : `(${first})`;
}
